// Generates THIRD_PARTY_NOTICES.md from the Cargo lockfile graph of the shipped binaries and the npm runtime
// dependency tree, and fails if any license falls outside the allowlist.
//   node scripts/third-party-notices.mjs [--check]   (--check: verify the committed file is current)
import { spawnSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const ALLOWED = ['MIT', 'Apache-2.0', 'Apache-2.0 WITH LLVM-exception', 'BSD-2-Clause', 'BSD-3-Clause', 'ISC', 'Unicode-3.0', 'Unicode-DFS-2016', 'Zlib', 'CC0-1.0', 'MIT-0', 'Unlicense', 'BSL-1.0', 'CDLA-Permissive-2.0', '0BSD', 'MPL-2.0'];
const okExpression = (expr) => {
  if (!expr) return false;
  // An OR expression is fine when any branch is allowed; AND needs every part allowed.
  return expr.replace(/[()]/g, '').split(/\s+OR\s+|\//).some((alt) => alt.split(/\s+AND\s+/).every((p) => ALLOWED.includes(p.trim())));
};

const meta = spawnSync('cargo', ['metadata', '--format-version', '1', '--locked', '--manifest-path', join(root, 'rust', 'Cargo.toml')], { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
if (meta.status !== 0) { process.stderr.write(meta.stderr); process.exit(1); }
const data = JSON.parse(meta.stdout);
const byId = new Map(data.packages.map((p) => [p.id, p]));
const nodes = new Map(data.resolve.nodes.map((n) => [n.id, n]));
const shipped = data.packages.filter((p) => ['pedelec-ipc-worker', 'pedelec-agent', 'pedelec-cli'].includes(p.name)).map((p) => p.id);
const seen = new Set();
const visit = (id) => {
  if (seen.has(id)) return;
  seen.add(id);
  for (const dep of nodes.get(id)?.deps ?? []) {
    // Normal (runtime) dependencies only; build-deps compile into nothing shipped except proc-macros' output.
    if (dep.dep_kinds.some((k) => k.kind === null || k.kind === 'build')) visit(dep.pkg);
  }
};
shipped.forEach(visit);
const workspace = new Set(data.workspace_members);
const crates = [...seen].filter((id) => !workspace.has(id)).map((id) => byId.get(id)).sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const npmPackages = [];
const visitNpm = (name, from) => {
  const file = join(from, 'node_modules', name, 'package.json');
  const pkgFile = existsSync(file) ? file : join(root, 'node_modules', name, 'package.json');
  const pkg = JSON.parse(readFileSync(pkgFile, 'utf8'));
  if (npmPackages.some((p) => p.name === pkg.name && p.version === pkg.version)) return;
  npmPackages.push({ name: pkg.name, version: pkg.version, license: typeof pkg.license === 'string' ? pkg.license : pkg.license?.type, repository: typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url });
  for (const dep of Object.keys(pkg.dependencies ?? {})) visitNpm(dep, dirname(pkgFile));
};
const own = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
for (const dep of Object.keys(own.dependencies ?? {})) visitNpm(dep, root);
npmPackages.sort((a, b) => a.name.localeCompare(b.name));

const bad = [...crates.map((c) => ({ name: c.name, version: c.version, license: c.license })), ...npmPackages].filter((p) => !okExpression(p.license));
if (bad.length) { console.error(JSON.stringify({ ok: false, disallowedLicenses: bad }, null, 2)); process.exit(1); }

const lines = [
  '# Third-Party Notices',
  '',
  '`@kaoruisaac/pedelec-node` is MIT licensed (see `LICENSE`). Its native executables (`pedelec-ipc-worker`, `pedelec-agent`,',
  '`pedelec-cli`) statically link the Rust crates below, and its JavaScript depends on the npm packages below. Each is',
  'used under the license shown; full license texts are available from each project\'s repository and from the',
  'crates.io / npm registry entry for the exact version listed.',
  '',
  'This file is generated by `node scripts/third-party-notices.mjs`; do not edit by hand.',
  '',
  `## Rust crates (${crates.length})`,
  '',
  '| Crate | Version | License | Repository |',
  '| --- | --- | --- | --- |',
  ...crates.map((c) => `| ${c.name} | ${c.version} | ${c.license} | ${c.repository ?? ''} |`),
  '',
  `## npm runtime dependencies (${npmPackages.length})`,
  '',
  '| Package | Version | License | Repository |',
  '| --- | --- | --- | --- |',
  ...npmPackages.map((p) => `| ${p.name} | ${p.version} | ${p.license} | ${p.repository ?? ''} |`),
  '',
  '## Not included',
  '',
  'Provider CLIs (Codex, Claude Code, OpenCode, Cursor Agent, Antigravity), their credentials, and Ollama are **not**',
  'distributed in this package. Install and license them separately.',
  '',
];
const text = lines.join('\n');
const target = join(root, 'THIRD_PARTY_NOTICES.md');
if (process.argv.includes('--check')) {
  if (!existsSync(target) || readFileSync(target, 'utf8') !== text) { console.error('THIRD_PARTY_NOTICES.md is stale; run node scripts/third-party-notices.mjs'); process.exit(1); }
} else writeFileSync(target, text);
console.log(JSON.stringify({ ok: true, crates: crates.length, npm: npmPackages.length }));
